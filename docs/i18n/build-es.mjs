/**
 * Inject the Spanish dictionary into analisis.html.
 *
 * The document has to stay one self-contained file - it is read from disk, from a
 * network share and over file:// , and a second file fetched at runtime would be blocked
 * by CORS in exactly those cases. So the dictionary is written into the page as an inline
 * script, and this is the step that puts it there.
 *
 * Source of truth is es.json beside this file: keys are the data-t markers in the
 * document, values are the Spanish. A key that is absent simply stays English, which is
 * what lets the translation land in batches without ever shipping a half-swapped page.
 *
 *   node docs/i18n/build-es.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const docPath = join(here, '..', 'analisis.html');
const dict = JSON.parse(readFileSync(join(here, 'es.json'), 'utf8'));

const nav = dict._nav ?? {};
const blocks = { ...dict };
delete blocks._nav;

const doc = readFileSync(docPath, 'utf8');

// Every marker the document actually carries. A key for a marker that no longer exists is
// a translation of deleted text, and saying so here is cheaper than wondering later why a
// paragraph never switches.
const markers = new Set([...doc.matchAll(/data-t="(t\d+)"/g)].map((m) => m[1]));
const orphans = Object.keys(blocks).filter((k) => !markers.has(k));
if (orphans.length) {
  console.warn(`warning: ${orphans.length} key(s) match no marker: ${orphans.slice(0, 8).join(', ')}`);
}

const OPEN = '<script id="pacs-es">';
const CLOSE = '</' + 'script>';
const payload = `${OPEN}
/* Spanish dictionary - generated by docs/i18n/build-es.mjs, do not edit here. */
window.PACS_ES = ${JSON.stringify(blocks, null, 0)};
${CLOSE}`;

let out = doc;
const existing = out.indexOf(OPEN);
if (existing !== -1) {
  const end = out.indexOf(CLOSE, existing) + CLOSE.length;
  out = out.slice(0, existing) + payload + out.slice(end);
} else {
  // Before the behaviour script, so the dictionary is defined by the time boot() runs.
  const anchor = '<script>\n/* ============================================================';
  const at = out.indexOf(anchor);
  if (at === -1) throw new Error('could not find the behaviour script to insert before');
  out = out.slice(0, at) + payload + '\n' + out.slice(at);
}

// Section titles in the contents list are an attribute, not a marked block, so they are
// written onto the sections themselves rather than carried in the dictionary at runtime.
out = out.replace(/<section id="([^"]+)"([^>]*)>/g, (whole, id, rest) => {
  const cleaned = rest.replace(/ data-title-es="[^"]*"/, '');
  const es = nav[id];
  if (!es) return `<section id="${id}"${cleaned}>`;
  return `<section id="${id}"${cleaned} data-title-es="${es.replace(/"/g, '&quot;')}">`;
});

writeFileSync(docPath, out);

const total = markers.size;
const done = Object.keys(blocks).filter((k) => markers.has(k)).length;
const pct = total ? Math.round((done / total) * 100) : 0;
console.log(`injected ${done}/${total} blocks (${pct}%) and ${Object.keys(nav).length} section titles`);
