/**
 * Waiting-time fairness: the schema the deterministic ordering needs.
 *
 * Expand / migrate / contract, in that order, inside one migration:
 *   expand   - add the columns and tables, all nullable or defaulted
 *   migrate  - backfill participation_started_at, benefit_ended_at, counts_as_served and
 *              served_count from what the weighted-lottery model already stored
 *   contract - tighten the new columns, widen random_seed to bytea, drop fairness_state
 *              and ix_fairness_rank
 *
 * The principle behind all of it: nothing about waiting time is ever stored as a number
 * that something has to remember to update. Waiting time is decided_at minus an anchor,
 * computed at read time, so there is no counter to drift and no nightly job to fail.
 *
 * Written as raw SQL for the same reasons as the init migration: partial indexes, table
 * privileges and generated backfills are not things the DSL expresses well.
 */
